#!/bin/bash
# DS2-Anywhere interactive installer.
# Asks the few questions that matter, generates a config file, installs the
# systemd unit + cron + CLI symlink, prints next steps.
#
# Run as root from the cloned repo root:  sudo ./src/bin/install.sh

set -u

# --- helpers ---
RED=$'\033[0;31m' GREEN=$'\033[0;32m' YEL=$'\033[1;33m' BLUE=$'\033[0;34m' BOLD=$'\033[1m' RST=$'\033[0m'
say()  { echo "${BLUE}==>${RST} $*"; }
ok()   { echo "${GREEN}✓${RST} $*"; }
warn() { echo "${YEL}!${RST} $*"; }
die()  { echo "${RED}✗${RST} $*" >&2; exit 1; }

ask() {
  # ask "Prompt" "default" VAR_NAME
  local prompt="$1" default="$2" var="$3" answer
  if [ -n "$default" ]; then
    read -r -p "  ${prompt} [${BOLD}${default}${RST}]: " answer
    answer="${answer:-$default}"
  else
    read -r -p "  ${prompt}: " answer
  fi
  printf -v "$var" '%s' "$answer"
}

ask_secret() {
  local prompt="$1" var="$2" answer
  read -r -s -p "  ${prompt}: " answer; echo
  printf -v "$var" '%s' "$answer"
}

ask_yn() {
  # ask_yn "Prompt" "y|n" VAR_NAME
  local prompt="$1" default="$2" var="$3" answer
  read -r -p "  ${prompt} [${BOLD}${default}${RST}]: " answer
  answer="${answer:-$default}"
  case "$answer" in
    y|Y|yes|YES) printf -v "$var" 1 ;;
    *)            printf -v "$var" 0 ;;
  esac
}

[ "$(id -u)" -eq 0 ] || die "Run me as root (sudo ./src/bin/install.sh)."

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
[ -f "$REPO_ROOT/src/bin/audio_cron.sh" ] || die "Run me from the cloned repo (couldn't find src/bin/audio_cron.sh)."

cat <<'BANNER'

   ┌────────────────────────────────────────────────────────────┐
   │                                                            │
   │           DS2-Anywhere — interactive installer             │
   │                                                            │
   │  We're going to ask you a handful of questions, generate   │
   │  a configuration file, install the cron + systemd + CLI.   │
   │                                                            │
   │  Anything you can't answer right now: keep the default.    │
   │  You can edit /etc/conv-dss-ds2-to-mp3/audio-cron.conf     │
   │  afterwards.                                               │
   │                                                            │
   └────────────────────────────────────────────────────────────┘

BANNER

# --- 1. installation location ---
say "Installation location"
ask "Install directory" "/opt/conv-dss-ds2-to-mp3" INSTALL_DIR
echo

# --- 2. audio filesystem ---
say "Audio storage layout"
ask "Root of your audio storage (where mail/, ftpsaisieaudio/ etc. live)" "/srv" AUDIO_ROOT
echo

# --- 3. DB mode ---
say "Database integration (mode 2 auto-feed)"
echo "  In DB mode, the cron queries your pipeline DB for active commands with DS2/DSS"
echo "  in the subject line, and scans only those mail folders. In no-DB mode it just"
echo "  scans the audio_aconv folder. Pick what you need."
ask_yn "Enable DB mode? (yes/no)" "yes" USE_DB
if [ "$USE_DB" = 1 ]; then
  ask        "  DB host"                 "127.0.0.1" DB_HOST
  ask        "  DB user"                 ""          DB_USER
  ask_secret "  DB password"                         DB_PASS
  ask        "  DB name"                 ""          DB_NAME
fi
echo

# --- 4. alerts ---
say "Alerting"
ask "Email address for conversion-failure alerts (empty = no alerts)" "" ALERT_EMAIL
echo

# --- 5. prerequisites check ---
say "Checking prerequisites"
NEEDED_OK=1
for cmd in node ffmpeg mysql dss-decode-native; do
  if command -v "$cmd" >/dev/null 2>&1; then
    ok "$cmd found at $(command -v "$cmd")"
  else
    warn "$cmd NOT found — you'll need to install it before this works"
    NEEDED_OK=0
  fi
done
if [ "$NEEDED_OK" = 0 ]; then
  echo
  warn "Some prerequisites are missing. Install hints:"
  echo "    Node.js : sudo apt install nodejs   (need >= 18)"
  echo "    ffmpeg  : sudo apt install ffmpeg"
  echo "    mysql   : sudo apt install mariadb-client"
  echo "    dss-decode-native : build from https://github.com/gaspardpetit/dss-codec"
  echo "                        ( cargo build --release  →  copy to /usr/local/bin )"
  echo "                        OR use this repo's Dockerfile which builds it."
  echo
  ask_yn "Continue with the install anyway?" "no" CONTINUE_ANYWAY
  [ "$CONTINUE_ANYWAY" = 1 ] || die "Aborted."
fi
echo

# --- 6. write the config ---
say "Writing config to /etc/conv-dss-ds2-to-mp3/audio-cron.conf"
mkdir -p /etc/conv-dss-ds2-to-mp3
cat > /etc/conv-dss-ds2-to-mp3/audio-cron.conf <<EOF
# Generated by install.sh on $(date '+%F %T')
# Edit freely. Format: shell variable assignments.

AUDIO_ROOT_PREFIX=${AUDIO_ROOT}

SRC=\${AUDIO_ROOT_PREFIX}/ftpsaisieaudio/faudio/audio_aconv
DST_MAIL_BASE=\${AUDIO_ROOT_PREFIX}/ftpmadactylo/mail
DST_FTP_BASE=\${AUDIO_ROOT_PREFIX}/ftpsaisieaudio/41
DST_STT_BASE=\${AUDIO_ROOT_PREFIX}/ftpsaisieaudio/tmp_audio_speechtotext

LOG_FILE=/var/log/audio_converter.log

USE_DB=${USE_DB}
DB_HOST=${DB_HOST:-127.0.0.1}
DB_USER=${DB_USER:-}
DB_PASS=${DB_PASS:-}
DB_NAME=${DB_NAME:-}

ALERT_EMAIL=${ALERT_EMAIL}

CLI=/usr/local/bin/conv-dss-ds2-to-mp3
NATIVE=/usr/local/bin/dss-decode-native
FFMPEG=/usr/bin/ffmpeg
EOF
chmod 640 /etc/conv-dss-ds2-to-mp3/audio-cron.conf
ok "Config written (mode 640, root-only readable since it contains a password)."
echo

# --- 7. copy project files ---
say "Installing project to ${INSTALL_DIR}"
mkdir -p "$INSTALL_DIR"
cp -r "$REPO_ROOT/src" "$INSTALL_DIR/"
chmod +x "$INSTALL_DIR/src/bin/"*
ok "Files copied."
echo

# --- 8. CLI symlink ---
say "Installing CLI symlink"
ln -sf "$INSTALL_DIR/src/bin/conv-dss-ds2-to-mp3" /usr/local/bin/conv-dss-ds2-to-mp3
ok "/usr/local/bin/conv-dss-ds2-to-mp3 -> $INSTALL_DIR/src/bin/conv-dss-ds2-to-mp3"
echo

# --- 9. systemd unit ---
say "Installing systemd unit (audio-convert.service)"
sed -e "s|/opt/conv-dss-ds2-to-mp3|$INSTALL_DIR|g" \
    "$INSTALL_DIR/src/etc/audio-convert.service" > /etc/systemd/system/audio-convert.service
chmod 644 /etc/systemd/system/audio-convert.service
systemctl daemon-reload
ok "Unit installed. Start with: systemctl enable --now audio-convert"
echo

# --- 10. cron ---
say "Installing cron (/etc/cron.d/audio_converter)"
sed -e "s|/opt/conv-dss-ds2-to-mp3|$INSTALL_DIR|g" \
    "$INSTALL_DIR/src/etc/audio_converter.cron" > /etc/cron.d/audio_converter
chmod 644 /etc/cron.d/audio_converter
ok "Cron installed (runs every minute, with flock to prevent overlap)."
echo

# --- 11. recap ---
cat <<RECAP

${GREEN}${BOLD}Installation complete.${RST}

Next steps:

  ${BOLD}1.${RST} Start the HTTP daemon (for the web UI):
       sudo systemctl enable --now audio-convert
       systemctl status audio-convert

  ${BOLD}2.${RST} Verify the CLI works:
       conv-dss-ds2-to-mp3 --help

  ${BOLD}3.${RST} Check the cron is firing (wait ~1 min, then):
       tail -f /var/log/audio_converter.log

  ${BOLD}4.${RST} If you want the web UI, copy src/web/convertisseur.php into
     your admin area (it's PHP 5.6 compatible). It posts to 127.0.0.1:8765
     where the daemon listens.

  ${BOLD}5.${RST} Tweak ${BOLD}/etc/conv-dss-ds2-to-mp3/audio-cron.conf${RST} anytime
     to change paths, DB creds, alerting, etc.

Rollback:
   sudo systemctl disable --now audio-convert
   sudo rm /etc/cron.d/audio_converter /etc/systemd/system/audio-convert.service
   sudo rm /usr/local/bin/conv-dss-ds2-to-mp3
   sudo rm -rf ${INSTALL_DIR} /etc/conv-dss-ds2-to-mp3

Documentation: https://github.com/Guillain-RDCDE/DS2-Anywhere

RECAP
